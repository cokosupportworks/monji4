const fs=require('node:fs'),path=require('node:path');
const sources=['stroke-data.js','core.js','lessons.js','backup.js','archive.js','journey.js','stations.js','word-archive.js','opening.js','app.js'];
const version=JSON.parse(fs.readFileSync(path.join(__dirname,'package.json'),'utf8')).version;
const content='/* もんじぼたる４ runtime '+version+' — generated by node build.cjs */\n'+sources.map(file=>'\n/* '+file+' */\n'+fs.readFileSync(path.join(__dirname,file),'utf8')).join('\n;\n');
const target=path.join(__dirname,'runtime.js');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content){console.error('runtime.js is out of date. Run npm run build.');process.exit(1);}}
else fs.writeFileSync(target,content);
